let deferredPrompt: any = null;
let isPromptReady = false;

if (typeof window !== 'undefined') {
  window.addEventListener('beforeinstallprompt', (e) => {
    e.preventDefault();
    deferredPrompt = e;
    isPromptReady = true;
    window.dispatchEvent(new CustomEvent('pwa_prompt_ready'));
  });

  window.addEventListener('appinstalled', () => {
    deferredPrompt = null;
    isPromptReady = false;
    window.dispatchEvent(new CustomEvent('pwa_installed'));
  });
}

export function isPWAInstallAvailable(): boolean {
  return isPromptReady;
}

export async function promptPWAInstall(): Promise<{ outcome: 'accepted' | 'dismissed' | 'unsupported' }> {
  if (!deferredPrompt) {
    return { outcome: 'unsupported' };
  }

  try {
    deferredPrompt.prompt();
    const choiceResult = await deferredPrompt.userChoice;
    deferredPrompt = null;
    isPromptReady = false;
    return { outcome: choiceResult.outcome };
  } catch (err) {
    console.error('PWA install error:', err);
    return { outcome: 'unsupported' };
  }
}

